/**
 * build-auto-loader.js
 * Scans all HTML files in the project root, discovers every *-slot id,
 * maps each to its components/*.html counterpart, then writes
 * dist/js/auto-loader.js — a self-contained ES module that can be
 * dropped into any page with:
 *   <script type="module" src="dist/js/auto-loader.js"></script>
 */

'use strict';

const fs   = require('fs');
const path = require('path');

// ── Config ────────────────────────────────────────────────────────────────────
const ROOT       = __dirname;
const COMP_DIR   = path.join(ROOT, 'components');
const OUT_FILE   = path.join(ROOT, 'dist', 'js', 'auto-loader.js');
const HTML_GLOB  = ['index.html', 'about.html', 'contact.html', 'upcoming.html'];

// ── Helpers ───────────────────────────────────────────────────────────────────

/** Return every id="*-slot" found in an HTML string */
function extractSlots(html) {
  const re = /id="([a-zA-Z0-9_-]+-slot)"/g;
  const slots = new Set();
  let m;
  while ((m = re.exec(html)) !== null) slots.add(m[1]);
  return [...slots];
}

/** Convert a slot id like "header-slot" → "components/header.html" */
function slotToPath(slotId) {
  const name = slotId.replace(/-slot$/, '');
  return `components/${name}.html`;
}

// ── Scan HTML files ───────────────────────────────────────────────────────────
const configMap = new Map(); // selector → path (deduped)

for (const file of HTML_GLOB) {
  const full = path.join(ROOT, file);
  if (!fs.existsSync(full)) continue;

  const html  = fs.readFileSync(full, 'utf8');
  const slots = extractSlots(html);

  for (const slot of slots) {
    const compPath = slotToPath(slot);
    const compFull = path.join(ROOT, compPath);

    if (!fs.existsSync(compFull)) {
      console.warn(`  ⚠  Slot #${slot} found in ${file} but ${compPath} does not exist — skipping`);
      continue;
    }

    if (!configMap.has(slot)) {
      configMap.set(slot, compPath);
      console.log(`  ✓  #${slot}  →  ${compPath}  (from ${file})`);
    }
  }
}

if (configMap.size === 0) {
  console.warn('\n⚠  No slot/component pairs found. auto-loader.js will be empty.\n');
}

// ── Build the component configs array literal ─────────────────────────────────
const configEntries = [...configMap.entries()]
  .map(([sel, p]) => `  { selector: '#${sel}', path: '${p}' }`)
  .join(',\n');

// ── Generate output module ────────────────────────────────────────────────────
const output = `/**
 * auto-loader.js  (auto-generated by build-auto-loader.js — do not edit)
 * Generated: ${new Date().toISOString()}
 *
 * Discovered ${configMap.size} component slot(s):
${[...configMap.entries()].map(([s, p]) => ` *   #${s}  →  ${p}`).join('\n')}
 */

import { ComponentLoader } from './component-loader.js';

const COMPONENTS = [
${configEntries}
];

async function bootLoader() {
  const loader = new ComponentLoader();
  try {
    await loader.loadComponents(COMPONENTS);
    console.log('[auto-loader] All ${configMap.size} component(s) loaded.');
  } catch (err) {
    console.error('[auto-loader] Failed to load components:', err);
  }
}

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', bootLoader);
} else {
  bootLoader();
}
`;

// ── Write output ──────────────────────────────────────────────────────────────
fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
fs.writeFileSync(OUT_FILE, output, 'utf8');

console.log(`\n✅  auto-loader.js written → dist/js/auto-loader.js  (${configMap.size} slot(s))\n`);
